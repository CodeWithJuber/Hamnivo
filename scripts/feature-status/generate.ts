/**
 * Renders docs/feature-status.md from:
 *   - docs/blueprint/Development-Backlog.csv  (232 blueprint feature IDs)
 *   - docs/design/UX-State-Matrix.csv         (168 HNV design states)
 *   - docs/status/evidence.json               (status + evidence per ID)
 *
 * A status other than "planned" must cite evidence (source or test paths) that exists on disk.
 * Run: pnpm exec tsx scripts/feature-status/generate.ts [--check]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

export const STATUSES = [
  'planned',
  'in-progress',
  'implemented',
  'implemented-live-unverified',
  'inherited',
  'partial',
  'interface-only',
  'deferred',
] as const;
type Status = (typeof STATUSES)[number];

interface Evidence {
  status: Status;
  evidence?: string[];
  note?: string;
}

/** RFC 4180 CSV parser (quoted fields, escaped quotes, embedded newlines). */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let quoted = false;
  const input = text.replace(/^\uFEFF/, '');
  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (quoted) {
      if (ch === '"') {
        if (input[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          quoted = false;
        }
      } else {
        field += ch;
      }
      continue;
    }
    if (ch === '"') quoted = true;
    else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && input[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      if (row.some((cell) => cell.length > 0)) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    if (row.some((cell) => cell.length > 0)) rows.push(row);
  }
  return rows;
}

function readTable(path: string): Record<string, string>[] {
  const [header, ...rows] = parseCsv(readFileSync(join(root, path), 'utf8'));
  if (!header) throw new Error(`${path} is empty`);
  return rows.map((cells) => Object.fromEntries(header.map((key, i) => [key, cells[i] ?? ''])));
}

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function render(): { markdown: string; problems: string[] } {
  const backlog = readTable('docs/blueprint/Development-Backlog.csv');
  const states = readTable('docs/design/UX-State-Matrix.csv');
  const evidencePath = join(root, 'docs/status/evidence.json');
  const evidence: Record<string, Evidence> = existsSync(evidencePath)
    ? JSON.parse(readFileSync(evidencePath, 'utf8'))
    : {};
  const problems: string[] = [];
  const known = new Set([...backlog.map((r) => r.ID), ...states.map((r) => r.ID)]);

  for (const [id, entry] of Object.entries(evidence)) {
    if (!known.has(id)) problems.push(`${id}: not a known feature or state ID`);
    if (!STATUSES.includes(entry.status)) problems.push(`${id}: unknown status "${entry.status}"`);
    if (entry.status !== 'planned' && entry.status !== 'deferred' && !entry.evidence?.length) {
      problems.push(`${id}: status "${entry.status}" requires evidence paths`);
    }
    for (const path of entry.evidence ?? []) {
      if (!existsSync(join(root, path))) problems.push(`${id}: evidence path missing: ${path}`);
    }
  }

  const statusOf = (id: string): Evidence => evidence[id] ?? { status: 'planned' };
  const counts = (ids: string[]) => {
    const tally = new Map<Status, number>();
    for (const id of ids) tally.set(statusOf(id).status, (tally.get(statusOf(id).status) ?? 0) + 1);
    return STATUSES.filter((s) => tally.get(s))
      .map((s) => `${s}: ${tally.get(s)}`)
      .join(' · ');
  };

  const lines: string[] = [
    '# Hamnivo feature status',
    '',
    '> Generated by `scripts/feature-status/generate.ts` from the blueprint backlog, the UX state',
    '> matrix and `docs/status/evidence.json`. Do not edit by hand.',
    '',
    'Statuses: `implemented` (code + automated tests), `implemented-live-unverified` (tested against',
    'fakes/fixtures, not against the live third-party service), `inherited` (provided by Chatwoot CE and',
    'verified through the adapter), `partial`, `interface-only`, `in-progress`, `deferred`, `planned`.',
    '',
    `**Blueprint features (${backlog.length}):** ${counts(backlog.map((r) => r.ID))}`,
    '',
    `**Design states (${states.length}):** ${counts(states.map((r) => r.ID))}`,
    '',
    '## Blueprint features',
    '',
  ];

  const modules = [...new Set(backlog.map((r) => r.Module))];
  for (const module of modules) {
    const rows = backlog.filter((r) => r.Module === module);
    lines.push(
      `### ${module}`,
      '',
      '| ID | Feature | Priority | Wave | Status | Evidence / note |',
      '|---|---|---|---|---|---|',
    );
    for (const r of rows) {
      const e = statusOf(r.ID);
      const detail = [e.evidence?.map((p) => `\`${p}\``).join(', '), e.note]
        .filter(Boolean)
        .join(' — ');
      lines.push(
        `| ${r.ID} | ${escapeCell(r.Feature)} | ${r.Priority} | ${r['Release wave']} | ${e.status} | ${escapeCell(detail)} |`,
      );
    }
    lines.push('');
  }

  lines.push('## Design states (UX state matrix)', '');
  const groups = [...new Set(states.map((r) => r.group))];
  for (const group of groups) {
    const rows = states.filter((r) => r.group === group);
    lines.push(
      `### ${group}`,
      '',
      '| ID | Screen | State | Status | Evidence / note |',
      '|---|---|---|---|---|',
    );
    for (const r of rows) {
      const e = statusOf(r.ID);
      const detail = [e.evidence?.map((p) => `\`${p}\``).join(', '), e.note]
        .filter(Boolean)
        .join(' — ');
      lines.push(
        `| ${r.ID} | ${escapeCell(r.screen)} | ${escapeCell(r.state)} | ${e.status} | ${escapeCell(detail)} |`,
      );
    }
    lines.push('');
  }
  return { markdown: `${lines.join('\n')}\n`, problems };
}

const { markdown, problems } = render();
const target = join(root, 'docs/feature-status.md');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== markdown) problems.push('docs/feature-status.md is stale; run the generator');
} else {
  writeFileSync(target, markdown);
}
if (problems.length) {
  console.error(problems.map((p) => `- ${p}`).join('\n'));
  process.exit(1);
}
