/**
 * Writes docs/licenses.md from `pnpm licenses list --json` (blueprint E09: exact versions and
 * distribution obligations recorded before reuse). Licenses outside the allowlist are flagged for
 * review and make `--check` fail, so a new dependency with unusual terms cannot slip in unnoticed.
 *
 * Run: pnpm exec tsx scripts/licenses/inventory.ts [--check]
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Permissive licenses that need attribution only. */
const PERMISSIVE = new Set([
  'MIT',
  'MIT-0',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'Apache-2.0',
  'BlueOak-1.0.0',
  'CC0-1.0',
  'CC-BY-4.0',
  'Unlicense',
  'Python-2.0',
  'Zlib',
  'OFL-1.1',
]);
/** Weak copyleft: allowed unmodified as a dependency; modifications must be published. */
const WEAK_COPYLEFT = new Set(['MPL-2.0', 'LGPL-3.0-or-later', 'LGPL-2.1-or-later', 'EPL-2.0']);

/** Reviewed exceptions: package → reason. Keep this list short and explicit. */
const REVIEWED: Record<string, string> = {};

interface Entry {
  name: string;
  versions: string[];
  license: string;
  homepage?: string;
}

/** Non-SPDX spellings some packages declare, mapped to their SPDX identifiers. */
const ALIASES: Record<string, string> = {
  'MIT License': 'MIT',
  'The MIT License': 'MIT',
  'Apache License 2.0': 'Apache-2.0',
  'Apache 2.0': 'Apache-2.0',
  'ISC License': 'ISC',
};

function classify(license: string): 'permissive' | 'weak-copyleft' | 'review' {
  const parts = license
    .replace(/[()]/g, '')
    .split(/\s+(?:OR|AND)\s+/i)
    .map((p) => ALIASES[p.trim()] ?? p.trim());
  const isOr = /\sOR\s/i.test(license);
  const ok = (p: string) => PERMISSIVE.has(p);
  if (isOr ? parts.some(ok) : parts.every(ok)) return 'permissive';
  if (
    parts.some((p) => WEAK_COPYLEFT.has(p)) &&
    parts.every((p) => ok(p) || WEAK_COPYLEFT.has(p))
  ) {
    return 'weak-copyleft';
  }
  return 'review';
}

const raw = execFileSync('pnpm', ['licenses', 'list', '--json'], { cwd: root, encoding: 'utf8' });
const grouped = JSON.parse(raw) as Record<string, Entry[]>;
const entries = Object.values(grouped)
  .flat()
  .sort((a, b) => a.name.localeCompare(b.name));

const flagged = entries.filter((e) => classify(e.license) === 'review' && !REVIEWED[e.name]);
const lines = [
  '# Third-party license inventory',
  '',
  '> Generated by `scripts/licenses/inventory.ts` from the pnpm lockfile. Do not edit by hand.',
  '',
  `Packages: ${entries.length}. Needing review: ${flagged.length}.`,
  '',
  '| Package | Version(s) | License | Class |',
  '|---|---|---|---|',
  ...entries.map((e) => {
    const cls = REVIEWED[e.name] ? `reviewed: ${REVIEWED[e.name]}` : classify(e.license);
    return `| ${e.name} | ${e.versions.join(', ')} | ${e.license} | ${cls} |`;
  }),
  '',
];
const markdown = `${lines.join('\n')}\n`;
const target = join(root, 'docs/licenses.md');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== markdown) {
    console.error('docs/licenses.md is stale; run scripts/licenses/inventory.ts');
    process.exit(1);
  }
} else {
  writeFileSync(target, markdown);
}
if (flagged.length) {
  console.error(
    `Licenses needing review:\n${flagged.map((e) => `- ${e.name}: ${e.license}`).join('\n')}`,
  );
  process.exit(1);
}
