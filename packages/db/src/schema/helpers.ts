import { type SQL, sql } from 'drizzle-orm';
import { customType, pgPolicy, pgRole, timestamp, uuid } from 'drizzle-orm/pg-core';
import { uuidv7 } from 'uuidv7';

/** Roles come from deploy/postgres/bootstrap.sql; migrations never create or alter them. */
export const appRole = pgRole('hamnivo_app').existing();
export const platformRole = pgRole('hamnivo_platform').existing();

export const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType: () => 'bytea',
});

export const citext = customType<{ data: string; driverData: string }>({
  dataType: () => 'citext',
});

/** UUIDv7 primary key generated by the application (time-ordered, index friendly). */
export const id = () =>
  uuid('id')
    .primaryKey()
    .$defaultFn(() => uuidv7());

export const tstz = (name: string) => timestamp(name, { withTimezone: true });
export const createdAt = () => tstz('created_at').notNull().defaultNow();
export const updatedAt = () =>
  tstz('updated_at')
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());

/** `<column> = (select app.current_tenant())`: evaluated once per statement, not per row. */
function tenantMatch(column: string): SQL {
  return sql.raw(`${column} = (select app.current_tenant())`);
}

/**
 * Row-level security for tenant data: the application role only reads and writes rows of the
 * tenant set by withTenant(). With no tenant set, it sees nothing and cannot insert.
 */
export const tenantIsolation = (column = 'tenant_id') =>
  pgPolicy('tenant_isolation', {
    as: 'permissive',
    for: 'all',
    to: appRole,
    using: tenantMatch(column),
    withCheck: tenantMatch(column),
  });

/** Read-only metadata access for the platform console (granted per table in SQL). */
export const platformRead = () =>
  pgPolicy('platform_read', {
    as: 'permissive',
    for: 'select',
    to: platformRole,
    using: sql`true`,
  });
