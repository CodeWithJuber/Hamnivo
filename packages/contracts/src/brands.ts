import { z } from 'zod';
import { Timestamp } from './common.js';
import { typeId } from './ids.js';

/** A website origin (scheme, host and optional port; no path), e.g. `https://shop.example.com`. */
export const WebOrigin = z
  .string()
  .max(300)
  .regex(/^https?:\/\/[^/?#\s]+$/, 'Expected an origin such as https://shop.example.com')
  .transform((value) => new URL(value).origin);

export const BrandStatus = z.enum(['active', 'disabled']);

export const CreateBrandRequest = z
  .object({
    workspaceId: typeId('workspace'),
    name: z.string().trim().min(1).max(80),
    /** Websites allowed to embed this brand's chat widget. */
    allowedOrigins: z.array(WebOrigin).max(50).default([]),
  })
  .meta({ id: 'CreateBrandRequest' });

/** Rename a brand or replace the websites allowed to embed its chat; at least one of the two. */
export const UpdateBrandRequest = z
  .object({
    name: z.string().trim().min(1).max(80).optional(),
    /** The full new list; websites left out can no longer load the chat, and their chats end. */
    allowedOrigins: z.array(WebOrigin).max(50).optional(),
  })
  .refine((v) => v.name !== undefined || v.allowedOrigins !== undefined, {
    message: 'Send a new name, new allowed websites or both',
  })
  .meta({ id: 'UpdateBrandRequest' });

const LocalTime = z
  .string()
  .regex(/^(([01]\d|2[0-3]):[0-5]\d|24:00)$/, 'Use 24-hour HH:MM, such as 09:30');

/** One opening span in the brand's local time; it may not cross midnight (split it in two). */
export const OpeningInterval = z
  .object({ open: LocalTime, close: LocalTime })
  .refine((v) => v.open !== '24:00' && v.open < v.close, {
    message: 'Opening must come before closing',
    path: ['close'],
  });

const OpeningDay = z
  .array(OpeningInterval)
  .max(6)
  .refine(
    (spans) =>
      [...spans]
        .sort((a, b) => (a.open < b.open ? -1 : 1))
        .every((span, i, all) => i === 0 || (all[i - 1] as typeof span).close <= span.open),
    { message: 'Opening spans on one day must not overlap' },
  );

/**
 * When people answer (W11). The widget says honestly whether someone is working now and when
 * people are back; the AI keeps answering at any hour.
 */
export const BusinessHours = z
  .object({
    /** IANA time zone, such as `Asia/Karachi`. */
    timezone: z
      .string()
      .min(1)
      .max(64)
      .refine(
        (tz) => {
          try {
            new Intl.DateTimeFormat('en', { timeZone: tz });
            return true;
          } catch {
            return false;
          }
        },
        { message: 'Unknown time zone' },
      ),
    weekly: z.object({
      sun: OpeningDay,
      mon: OpeningDay,
      tue: OpeningDay,
      wed: OpeningDay,
      thu: OpeningDay,
      fri: OpeningDay,
      sat: OpeningDay,
    }),
    /** Whole local days without service, such as public holidays (YYYY-MM-DD). */
    closedDates: z.array(z.iso.date()).max(366).default([]),
  })
  .meta({ id: 'BusinessHours' });
export type BusinessHours = z.infer<typeof BusinessHours>;

export const SetBusinessHoursRequest = z
  .object({
    /** `null` removes the hours: the widget then never claims a person is available. */
    businessHours: BusinessHours.nullable(),
  })
  .meta({ id: 'SetBusinessHoursRequest' });

export const Brand = z
  .object({
    id: typeId('brand'),
    workspaceId: typeId('workspace'),
    name: z.string(),
    /** Public widget identifier for the loader snippet; not a credential. */
    widgetId: typeId('widget'),
    allowedOrigins: z.array(z.string()),
    businessHours: BusinessHours.nullable(),
    status: BrandStatus,
    createdAt: Timestamp,
  })
  .meta({ id: 'Brand' });
export type Brand = z.infer<typeof Brand>;

/** Signature algorithms accepted for customer identity assertions (W12). */
export const IdentityKeyAlg = z.enum(['ES256', 'EdDSA', 'RS256', 'HS256']);

/**
 * A key that verifies the identity assertions a brand's backend signs for its customers. Public
 * keys are stored as given; an HS256 secret is generated by Hamnivo and shown once.
 */
export const IdentityKey = z
  .object({
    /** Key id; assertions name it in their `kid` header. */
    kid: z.string(),
    alg: IdentityKeyAlg,
    /** `retiring` still verifies (for a rotation); `revoked` never does. */
    status: z.enum(['active', 'retiring', 'revoked']),
    /** The public key, for asymmetric algorithms. */
    publicJwk: z.record(z.string(), z.unknown()).nullable(),
    createdAt: Timestamp,
    retiredAt: Timestamp.nullable(),
  })
  .meta({ id: 'IdentityKey' });
export type IdentityKey = z.infer<typeof IdentityKey>;

const Kid = z
  .string()
  .regex(/^[A-Za-z0-9._-]{1,64}$/, 'Letters, digits, dot, underscore and dash; at most 64')
  .optional();

export const CreateIdentityKeyRequest = z
  .discriminatedUnion('alg', [
    z.object({
      alg: z.enum(['ES256', 'EdDSA', 'RS256']),
      /** The public key as a JWK. Private members (such as `d`) are refused. */
      publicJwk: z.record(z.string(), z.unknown()),
      kid: Kid,
    }),
    z.object({ alg: z.literal('HS256'), kid: Kid }),
  ])
  .meta({ id: 'CreateIdentityKeyRequest' });

export const CreatedIdentityKey = IdentityKey.extend({
  /** HS256 only: the shared secret (base64url). Shown once; Hamnivo keeps it encrypted. */
  secret: z.string().optional(),
}).meta({ id: 'CreatedIdentityKey' });
export type CreatedIdentityKey = z.infer<typeof CreatedIdentityKey>;

export const ConnectChatwootRequest = z
  .object({
    /** Brand whose conversations the new Chatwoot inbox carries. */
    brandId: typeId('brand'),
  })
  .meta({ id: 'ConnectChatwootRequest' });

export const AuthorityConnection = z
  .object({
    id: typeId('connection'),
    kind: z.literal('chatwoot'),
    baseUrl: z.url(),
    accountId: z.int().positive(),
    status: z.enum(['provisioning', 'active', 'degraded', 'disabled']),
    inboxes: z.array(
      z.object({
        id: typeId('inbox'),
        brandId: typeId('brand').nullable(),
        purpose: z.enum(['live', 'import']),
        externalInboxId: z.int().positive(),
      }),
    ),
    createdAt: Timestamp,
  })
  .meta({ id: 'AuthorityConnection' });
export type AuthorityConnection = z.infer<typeof AuthorityConnection>;
