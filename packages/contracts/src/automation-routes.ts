import { z } from 'zod';
import {
  Automation,
  AutomationList,
  AutomationOptions,
  AutomationRunList,
  AutomationVersionList,
  CreateAutomationRequest,
  PublishAutomationRequest,
  SaveAutomationRequest,
  SetAutomationEnabledRequest,
  UpdatePromptLimitsRequest,
} from './automations.js';
import type { RouteDef } from './routes.js';

const brandParams = z.object({ brandId: z.string().meta({ description: 'Brand ID (brd_…)' }) });
const automationParams = z.object({
  automationId: z.string().meta({ description: 'Automation ID (aut_…)' }),
});

/** Automations (G21): website prompts and chat rules, edited as drafts and published. */
export const automationRoutes = {
  listAutomations: {
    method: 'get',
    path: '/v1/admin/brands/{brandId}/automations',
    operationId: 'listAutomations',
    summary: 'The brand’s automations, with what each did this week (automations.read)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: brandParams,
    success: { status: 200, description: 'Automations', schema: AutomationList },
  },
  createAutomation: {
    method: 'post',
    path: '/v1/admin/brands/{brandId}/automations',
    operationId: 'createAutomation',
    summary: 'Create an automation as a draft, or publish it at once (automations.manage)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: brandParams,
    body: CreateAutomationRequest,
    success: { status: 201, description: 'The new automation', schema: Automation },
  },
  getAutomationOptions: {
    method: 'get',
    path: '/v1/admin/brands/{brandId}/automations/options',
    operationId: 'getAutomationOptions',
    summary: 'The tags and support teams an automation can use (automations.read)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: brandParams,
    success: { status: 200, description: 'Options', schema: AutomationOptions },
  },
  updatePromptLimits: {
    method: 'put',
    path: '/v1/admin/brands/{brandId}/automations/prompt-limits',
    operationId: 'updatePromptLimits',
    summary:
      'How many website prompts one visitor sees a day, and the quiet time after closing one (automations.manage)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: brandParams,
    body: UpdatePromptLimitsRequest,
    success: { status: 200, description: 'Automations', schema: AutomationList },
  },
  getAutomation: {
    method: 'get',
    path: '/v1/admin/automations/{automationId}',
    operationId: 'getAutomation',
    summary: 'One automation, its draft and what runs (automations.read)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams,
    success: { status: 200, description: 'Automation', schema: Automation },
  },
  saveAutomation: {
    method: 'put',
    path: '/v1/admin/automations/{automationId}',
    operationId: 'saveAutomation',
    summary: 'Save the draft; what runs changes only when it is published (automations.manage)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams,
    body: SaveAutomationRequest,
    success: { status: 200, description: 'Automation', schema: Automation },
  },
  publishAutomation: {
    method: 'post',
    path: '/v1/admin/automations/{automationId}/publish',
    operationId: 'publishAutomation',
    summary: 'Publish the draft as a new version, which runs from now on (automations.manage)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams,
    body: PublishAutomationRequest,
    success: { status: 200, description: 'Automation', schema: Automation },
  },
  setAutomationEnabled: {
    method: 'put',
    path: '/v1/admin/automations/{automationId}/enabled',
    operationId: 'setAutomationEnabled',
    summary: 'Turn an automation on or off (automations.manage)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams,
    body: SetAutomationEnabledRequest,
    success: { status: 200, description: 'Automation', schema: Automation },
  },
  deleteAutomation: {
    method: 'delete',
    path: '/v1/admin/automations/{automationId}',
    operationId: 'deleteAutomation',
    summary: 'Delete an automation with its versions and run history (automations.manage)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams,
    success: { status: 204, description: 'Deleted' },
  },
  listAutomationVersions: {
    method: 'get',
    path: '/v1/admin/automations/{automationId}/versions',
    operationId: 'listAutomationVersions',
    summary: 'Published versions, newest first (automations.read)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams,
    success: { status: 200, description: 'Versions', schema: AutomationVersionList },
  },
  restoreAutomationVersion: {
    method: 'post',
    path: '/v1/admin/automations/{automationId}/versions/{version}/restore',
    operationId: 'restoreAutomationVersion',
    summary: 'Copy a published version into the draft, to publish again (automations.manage)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams.extend({ version: z.coerce.number().int().positive() }),
    body: PublishAutomationRequest,
    success: { status: 200, description: 'Automation', schema: Automation },
  },
  listAutomationRuns: {
    method: 'get',
    path: '/v1/admin/automations/{automationId}/runs',
    operationId: 'listAutomationRuns',
    summary: 'What a chat rule did, newest first (automations.read)',
    tags: ['Automations'],
    auth: 'staff_session',
    params: automationParams,
    query: z.object({ limit: z.coerce.number().int().min(1).max(100).default(50) }),
    success: { status: 200, description: 'Runs', schema: AutomationRunList },
  },
} as const satisfies Record<string, RouteDef>;
