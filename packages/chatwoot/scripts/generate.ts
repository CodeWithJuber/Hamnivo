/**
 * Generates src/generated/chatwoot.ts from the vendored Chatwoot v4.18.0 OpenAPI document plus the
 * Hamnivo overlay. `--check` fails when the committed output is stale.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'generated', 'chatwoot.ts');

type Json = Record<string, unknown>;
const isObject = (v: unknown): v is Json =>
  typeof v === 'object' && v !== null && !Array.isArray(v);

/** Deep merge where the overlay adds or extends objects (arrays and scalars replace). */
function merge(base: Json, overlay: Json): Json {
  const result: Json = { ...base };
  for (const [key, value] of Object.entries(overlay)) {
    if (key === '$comment') continue;
    const existing = result[key];
    result[key] = isObject(existing) && isObject(value) ? merge(existing, value) : value;
  }
  return result;
}

const swagger = JSON.parse(
  readFileSync(join(root, 'swagger', 'v4.18.0', 'swagger.json'), 'utf8'),
) as Json;
const overlay = JSON.parse(readFileSync(join(root, 'swagger', 'overlay.json'), 'utf8')) as Json;
const ast = await openapiTS(merge(swagger, overlay) as never, { alphabetize: true });
const output = `/* Generated by scripts/generate.ts from Chatwoot v4.18.0 swagger + overlay. Do not edit. */\n${astToString(ast)}`;

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) {
    console.error(
      'src/generated/chatwoot.ts is stale; run pnpm --filter @hamnivo/chatwoot generate',
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
