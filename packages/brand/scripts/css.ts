/**
 * Generates assets/tokens.css (CSS custom properties) and assets/theme.css (Tailwind 4 theme)
 * from src/tokens.ts. `--check` fails when the committed files are stale.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  colors,
  controlHeight,
  motion,
  radius,
  type SemanticColors,
  shadow,
  typography,
  zIndex,
} from '../src/tokens.js';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const HEADER =
  '/* Generated by packages/brand/scripts/css.ts from src/tokens.ts. Do not edit. */\n';

function colorVars(set: SemanticColors, indent: string): string {
  return Object.entries(set)
    .map(([k, v]) => `${indent}--hv-${kebab(k)}: ${v};`)
    .join('\n');
}

export function tokensCss(): string {
  const shared = [
    `  --hv-font-sans: ${typography.fontSans};`,
    `  --hv-font-urdu: ${typography.fontUrdu};`,
    `  --hv-font-mono: ${typography.fontMono};`,
    ...Object.entries(radius).map(([k, v]) => `  --hv-radius-${k}: ${v};`),
    `  --hv-control-desktop: ${controlHeight.desktop};`,
    `  --hv-control-touch: ${controlHeight.touch};`,
    `  --hv-motion-fast: ${motion.fast};`,
    `  --hv-motion-base: ${motion.base};`,
    `  --hv-motion-slow: ${motion.slow};`,
    `  --hv-easing: ${motion.easing};`,
    ...Object.entries(shadow).map(([k, v]) => `  --hv-shadow-${k}: ${v};`),
    ...Object.entries(zIndex).map(([k, v]) => `  --hv-z-${k}: ${v};`),
  ].join('\n');
  return `${HEADER}
:root {
  color-scheme: light;
${colorVars(colors.light, '  ')}
${shared}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${colorVars(colors.dark, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${colorVars(colors.dark, '  ')}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --hv-motion-fast: 0ms;
    --hv-motion-base: 0ms;
    --hv-motion-slow: 0ms;
  }
}

:lang(ur) {
  --hv-font-sans: var(--hv-font-urdu);
}
`;
}

export function themeCss(): string {
  // The brand accent is exposed as `brand-*`: shadcn/ui reserves `accent` for neutral hovers.
  const reserved = new Set(['accent', 'accentStrong', 'accentSubtle', 'onAccentStrong']);
  const semantic = Object.keys(colors.light)
    .filter((k) => !reserved.has(k))
    .map((k) => `  --color-${kebab(k)}: var(--hv-${kebab(k)});`)
    .join('\n');
  const sizes = Object.entries(typography.size)
    .map(([k, [size, lh]]) => `  --text-${k}: ${size};\n  --text-${k}--line-height: ${lh};`)
    .join('\n');
  return `${HEADER}@import './tokens.css';

@theme {
  /* Only brand tokens are available as colours. */
  --color-*: initial;
}

@theme inline {
  --color-white: #ffffff;
  --color-black: #000000;
${semantic}
  --color-brand: var(--hv-accent);
  --color-brand-strong: var(--hv-accent-strong);
  --color-on-brand-strong: var(--hv-on-accent-strong);
  --color-brand-subtle: var(--hv-accent-subtle);

  /* shadcn/ui compatibility aliases */
  --color-background: var(--hv-bg);
  --color-foreground: var(--hv-text);
  --color-card: var(--hv-surface);
  --color-card-foreground: var(--hv-text);
  --color-popover: var(--hv-surface);
  --color-popover-foreground: var(--hv-text);
  --color-primary-foreground: var(--hv-on-primary);
  --color-secondary: var(--hv-surface-sunken);
  --color-secondary-foreground: var(--hv-text);
  --color-muted: var(--hv-surface-sunken);
  --color-muted-foreground: var(--hv-text-muted);
  --color-accent: var(--hv-surface-sunken);
  --color-accent-foreground: var(--hv-text);
  --color-destructive: var(--hv-danger);
  --color-input: var(--hv-border-input);
  --color-ring: var(--hv-focus);

  --font-sans: var(--hv-font-sans);
  --font-mono: var(--hv-font-mono);
${sizes}
  --radius-sm: var(--hv-radius-sm);
  --radius-md: var(--hv-radius-md);
  --radius-lg: var(--hv-radius-lg);
  --radius-xl: var(--hv-radius-xl);
  --shadow-sm: var(--hv-shadow-sm);
  --shadow-md: var(--hv-shadow-md);
  --shadow-lg: var(--hv-shadow-lg);
  --ease-standard: var(--hv-easing);
}

/* shadcn/ui components read this raw variable. */
:root {
  --radius: var(--hv-radius-md);
}
`;
}

const outputs = {
  'assets/tokens.css': tokensCss(),
  'assets/theme.css': themeCss(),
};
let stale = false;
for (const [file, content] of Object.entries(outputs)) {
  const target = join(pkg, file);
  if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
      console.error(`${file} is stale; run pnpm --filter @hamnivo/brand css`);
      stale = true;
    }
  } else {
    writeFileSync(target, content);
  }
}
if (stale) process.exit(1);
